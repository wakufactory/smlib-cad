import {readFile, writeFile} from "node:fs/promises";
import {build} from "esbuild";

const bundle = "html/source-editor.bundle.js";
const {metafile} = await build({
  entryPoints: ["editor/source-editor.mjs"],
  bundle: true,
  format: "iife",
  target: ["safari16", "chrome109", "firefox115"],
  minify: true,
  outfile: bundle,
  metafile: true,
  banner: {js: "// Generated by npm run build:editor. See source-editor.bundle.LICENSE.txt."},
});

const packages = new Set();
for (const path of Object.keys(metafile.outputs[bundle].inputs)) {
  const start = path.lastIndexOf("node_modules/");
  if (start === -1) continue;
  const [scope, name] = path.slice(start + "node_modules/".length).split("/");
  packages.add(path.slice(0, start) + "node_modules/" + (scope.startsWith("@") ? scope + "/" + name : scope));
}

const notices = await Promise.all([...packages].sort().map(async path => {
  const metadata = JSON.parse(await readFile(path + "/package.json", "utf8"));
  // UIW 4.25.12 omits LICENSE from both tarballs. Use the license from their shared release revision.
  // https://github.com/uiwjs/react-codemirror/blob/1e2e11f865860c6bd5029d71a2a09bd894ed5bad/LICENSE
  const upstreamLicense = ["@uiw/codemirror-theme-vscode", "@uiw/codemirror-themes"].includes(metadata.name)
    && metadata.version === "4.25.12";
  const license = await readFile(upstreamLicense ? "editor/licenses/uiw-4.25.12.txt" : path + "/LICENSE", "utf8");
  return metadata.name + " " + metadata.version + "\n\n" + license.trim();
}));
await writeFile("html/source-editor.bundle.LICENSE.txt", notices.join("\n\n---\n\n") + "\n");
